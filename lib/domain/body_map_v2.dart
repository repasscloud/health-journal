String bodySilhouetteV2(String view) =>
    _upperContour + (view == 'front' ? _frontFeet : _backFeet) + _lowerContour;

final _front = _parsePath(bodySilhouetteV2('front'));
final _back = _parsePath(bodySilhouetteV2('back'));

bool bodyContainsV2(double x, double y, String view) =>
    (view == 'front' ? _front : _back).contains(Offset(x * 100, y * 200));

Path _parsePath(String data) {
  final proxy = _SilhouettePath();
  writeSvgPathDataToPath(data, proxy);
  return proxy.path;
}

final class _SilhouettePath implements PathProxy {
  final path = Path();

  @override
  void moveTo(double x, double y) => path.moveTo(x, y);

  @override
  void lineTo(double x, double y) => path.lineTo(x, y);

  @override
  void cubicTo(
    double x1,
    double y1,
    double x2,
    double y2,
    double x3,
    double y3,
  ) => path.cubicTo(x1, y1, x2, y2, x3, y3);

  @override
  void close() => path.close();
}
